/** Tiny glyph showing n evenly spaced dots: used for subdivisions. */
export const SubdivGlyph = ({ n }: { n: number }) => (
  <svg width="40" height="14" viewBox="0 0 40 14" aria-hidden="true">
    <rect x="0" y="5.5" width="40" height="3" rx="1.5" fill="currentColor" opacity=".18" />
    {Array.from({ length: n }, (_, i) => (
      <circle key={i} cx={4 + (32 * i) / Math.max(1, n)} cy="7" r={i === 0 ? 4 : 2.6} fill="currentColor" />
    ))}
  </svg>
);
